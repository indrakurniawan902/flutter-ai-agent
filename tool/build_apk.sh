#!/bin/sh
# Builds a debug APK on this aarch64 host. The Android SDK ships x86-64-only host
# binaries (aapt2, cmake, ninja, zipalign, NDK clang), so they cannot exec unless the
# x86-64 system libraries are on LD_LIBRARY_PATH; without this the build dies with
# "cannot execute binary file" / missing libc.so.6 style loader errors.
set -eu

# Everything below is relative to the repo root, and the Gradle-daemon step in
# particular must run against the right tree, so resolve the root from this script's
# own location instead of trusting the caller's working directory.
script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(dirname -- "$script_dir")
cd "$repo_root"

# Entrypoint: the single un-flavored entrypoint lib/main.dart, or an explicit path
# passed as the first argument. The build is a plain `flutter build apk` — Flames has
# no flavors, so no flavor is ever named on the command line.
target="${1:-lib/main.dart}"
if [ ! -f "$target" ]; then
  echo "build_apk.sh: entrypoint not found: $target" >&2
  exit 1
fi

android_sdk="${ANDROID_SDK_ROOT:-/home/ubuntu/android-sdk}"

# Collect every installed NDK's host lib directory rather than assuming one: the
# effective NDK comes from the app's ndkVersion (which tracks the Flutter SDK and can
# change), and guessing a single version would silently drop the path it needs.
ndk_lib_dirs=""
for ndk in "${ANDROID_NDK_HOME:-}" "$android_sdk"/ndk/*; do
  [ -n "$ndk" ] || continue
  candidate="$ndk/toolchains/llvm/prebuilt/linux-x86_64/lib"
  [ -d "$candidate" ] && ndk_lib_dirs="$ndk_lib_dirs:$candidate"
done

LD_LIBRARY_PATH="/usr/x86_64-linux-gnu/lib:/home/ubuntu/android-build-libs/x86_64-linux-gnu$ndk_lib_dirs${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export LD_LIBRARY_PATH

echo "building $target"

# A Gradle daemon started without LD_LIBRARY_PATH keeps the broken environment for its
# whole lifetime, so stop any existing daemon to force a fresh one with the paths above.
# android/gradlew is git-ignored and generated by the Flutter tool, so it is absent on a
# fresh clone; Flutter regenerates it during the build below, meaning the very first
# build on such a clone may reuse a daemon started outside this script.
if [ -x android/gradlew ]; then
  (cd android && ./gradlew --stop) || true
else
  echo "note: android/gradlew absent (fresh clone) — no daemon to stop" >&2
fi

flutter build apk --debug -t "$target"
